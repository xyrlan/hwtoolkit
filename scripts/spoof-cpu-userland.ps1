#  Resumo + race-window disclosure
# ============================================================
Write-Host ""
Write-Host "  ============================================" -ForegroundColor Green
Write-Host "    CONCLUIDO!" -ForegroundColor Green
Write-Host "  ============================================" -ForegroundColor Green
Write-Host ""
Write-Host "  Task '$TaskName' registrada em '$TaskFolder' como SYSTEM." -ForegroundColor White
Write-Host "  Triggers: AtStartup + AtLogOn." -ForegroundColor White
Write-Host ""
Write-Host "  Race window (leia antes de rodar RubinOT):" -ForegroundColor Yellow
Write-Host "    - Trigger AtLogOn dispara APOS winlogon completar." -ForegroundColor Yellow
Write-Host "    - Se voce lancar RubinOT.exe antes disso (~2s pos-logon)," -ForegroundColor Yellow
Write-Host "      as strings ainda estarao originais no primeiro read." -ForegroundColor Yellow
Write-Host "    - Espere pelo evento EID 1000 no Event Log '$EventLogChannel'" -ForegroundColor Yellow
Write-Host "      (source $EventLogSource) antes de lancar o jogo." -ForegroundColor Yellow
Write-Host "    - Para eliminar a race, instale o driver (Level C):" -ForegroundColor Yellow
Write-Host "      .\03-instalar-driver.bat + .\scripts\spoof-smbios.ps1 -CpuOnly" -ForegroundColor Yellow
Write-Host ""
Write-Host "  Verificar estado:  .\scripts\spoof-cpu-userland.ps1 -Show" -ForegroundColor White
Write-Host "  Testar agora:      .\scripts\spoof-cpu-userland.ps1 -RunNow" -ForegroundColor White
Write-Host "  Desinstalar:       .\scripts\spoof-cpu-userland.ps1 -Uninstall" -ForegroundColor White
Write-Host ""

exit 0
